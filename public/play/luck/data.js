function randomIndex(length, random) {
  const value = Number(random());
  if (!Number.isFinite(value)) throw new TypeError('随机值必须是有限数字');
  return Math.min(length - 1, Math.max(0, Math.floor(value * length)));
}

function shuffled(items, random) {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index--) {
    const other = randomIndex(index + 1, random);
    [copy[index], copy[other]] = [copy[other], copy[index]];
  }
  return copy;
}

export class ContentPool {
  constructor() { this.reset(); }

  reset() {
    this.usedIds = new Set();
    this.previousIds = [];
  }

  draw(boardNumber, random = Math.random) {
    if (!Number.isInteger(boardNumber) || boardNumber < 1) {
      throw new RangeError('板数从 1 开始，且必须是整数');
    }
    const candidates = boardNumber <= 4
      ? ITEMS.filter(item => !this.usedIds.has(item.id))
      : ITEMS;
    if (candidates.length < 16) {
      throw new RangeError('前四板的未用文案不足 16 条，请重置本轮内容池');
    }
    const board = shuffled(candidates, random).slice(0, 16);
    if (board.every((item, index) => item.id === this.previousIds[index])) {
      [board[0], board[1]] = [board[1], board[0]];
    }
    if (boardNumber <= 4) board.forEach(item => this.usedIds.add(item.id));
    this.previousIds = board.map(item => item.id);
    return board;
  }
}

export function chooseQuote({ badLuckCount = 0, boardCount = 0 } = {}, previousId = null, random = Math.random) {
  let pool = badLuckCount >= 48 || boardCount >= 3
    ? 'praise'
    : badLuckCount < 16 ? 'small' : 'gentle';
  if (random() < 0.3) pool = 'joke';
  const options = QUOTES[pool].filter(quote => quote.id !== previousId);
  const quote = options[randomIndex(options.length, random)];
  return { ...quote, pool };
}
